fn main() -> std::result::Result<(), Box<dyn std::error::Error>> {
    let args: Vec<String> = std::env::args().collect();
    let out_dir = if args.len() > 1 {
        PathBuf::from(&args[1])
    } else if std::path::Path::new("src-tauri").is_dir() {
        PathBuf::from("src/types/generated")
    } else {
        PathBuf::from("../src/types/generated")
    };

    fs::create_dir_all(&out_dir)?;

    export_twofa_types(&out_dir)?;
    export_terminal_types(&out_dir)?;
    export_sync_types(&out_dir)?;
    export_mcp_types(&out_dir)?;

    println!(
        "Successfully exported TypeScript bindings to {}",
        out_dir.display()
    );
    Ok(())
}
