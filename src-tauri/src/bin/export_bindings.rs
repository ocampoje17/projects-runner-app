use std::fs;
use std::path::PathBuf;
use ts_rs::TS;

// Allow accessing crate types from lib
use tauri_app_lib::data_sync::*;
use tauri_app_lib::mcp::types::*;
use tauri_app_lib::terminal_types::*;
use tauri_app_lib::twofa::*;

fn export_sync_types(out_dir: &PathBuf) -> std::io::Result<()> {
    let cfg = ts_rs::Config::default();
    let declarations = [
        SyncScopes::decl(&cfg),
        SyncStatus::decl(&cfg),
        SyncLink::decl(&cfg),
        SyncLinkCandidate::decl(&cfg),
        SyncConflict::decl(&cfg),
        SyncPreview::decl(&cfg),
        SyncResult::decl(&cfg),
    ];
    let content = format!(
        "// This file was generated by [ts-rs]. Do not edit manually.\n\n{}\n",
        declarations
            .iter()
            .map(|d| format!("export {d};\n"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    fs::write(out_dir.join("sync.ts"), content)
}

fn export_twofa_types(out_dir: &PathBuf) -> std::io::Result<()> {
    let cfg = ts_rs::Config::default();
    let mut content =
        String::from("// This file was generated by [ts-rs]. Do not edit manually.\n\n");

    let decls = [
        LockTimeSetting::decl(&cfg),
        HideTokenSetting::decl(&cfg),
        ClearClipboardSetting::decl(&cfg),
        SortOrderSetting::decl(&cfg),
        CredentialStoreStatus::decl(&cfg),
        TwofaVaultSettings::decl(&cfg),
        TwofaPlatformCapabilities::decl(&cfg),
        TwofaVaultStatus::decl(&cfg),
        TwofaAccountSecretPayload::decl(&cfg),
        TwofaAccountSummary::decl(&cfg),
        TwofaAccountInput::decl(&cfg),
        TwofaCodeItem::decl(&cfg),
        TwofaCodeBatch::decl(&cfg),
        TwofaCopyResult::decl(&cfg),
        ImportAction::decl(&cfg),
        TwofaImportPreviewItem::decl(&cfg),
        TwofaImportPreview::decl(&cfg),
        CommitImportItemSelection::decl(&cfg),
        TwofaImportCommitResult::decl(&cfg),
        ProjectDelete2faPreview::decl(&cfg),
        TwofaScanScreenResult::decl(&cfg),
        TwofaVaultStateChangedEvent::decl(&cfg),
        TwofaSecurityError::decl(&cfg),
    ];

    for decl in decls {
        content.push_str("export ");
        content.push_str(&decl);
        content.push_str(";\n\n");
    }

    let target_file = out_dir.join("twofa.ts");
    fs::write(target_file, format!("{}\n", content.trim_end()))
}

